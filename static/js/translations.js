function changeLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) langCode = 'en';
  localStorage.setItem('disaster_sys_lang', langCode);

  const dict = TRANSLATIONS[langCode];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  const langSelectorBtn = document.getElementById('currentLangLabel');
  if (langSelectorBtn) {
    const names = { en: 'English', ta: 'தமிழ்', te: 'తెలుగు', hi: 'हिन्दी' };
    langSelectorBtn.textContent = names[langCode] || 'Language';
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('disaster_sys_lang') || 'en';
  changeLanguage(savedLang);

  document.querySelectorAll('.lang-select-item').forEach(item => {
    item.addEventListener('click', (e) => {
      e.preventDefault();
      const code = item.getAttribute('data-lang');
      changeLanguage(code);
    });
  });
});
